/**
 * Robots.txt Manager
 * Generate and manage robots.txt with SEO best practices
 */

export interface RobotsTxtConfig {
  userAgents: UserAgentRule[];
  sitemaps: string[];
  customRules?: string;
}

export interface UserAgentRule {
  userAgent: string;
  allow?: string[];
  disallow?: string[];
  crawlDelay?: number;
}

export function generateRobotsTxt(config: RobotsTxtConfig, platform: "wordpress" | "woocommerce"): string {
  let content = "# Robots.txt generated by SEO Max\n";
  content += `# Platform: ${platform}\n`;
  content += `# Generated: ${new Date().toISOString()}\n\n`;

  // User agents
  for (const rule of config.userAgents) {
    content += `User-agent: ${rule.userAgent}\n`;

    if (rule.allow && rule.allow.length > 0) {
      for (const path of rule.allow) {
        content += `Allow: ${path}\n`;
      }
    }

    if (rule.disallow && rule.disallow.length > 0) {
      for (const path of rule.disallow) {
        content += `Disallow: ${path}\n`;
      }
    }

    if (rule.crawlDelay) {
      content += `Crawl-delay: ${rule.crawlDelay}\n`;
    }

    content += "\n";
  }

  // Sitemaps
  for (const sitemap of config.sitemaps) {
    content += `Sitemap: ${sitemap}\n`;
  }

  // Custom rules
  if (config.customRules) {
    content += "\n# Custom Rules\n";
    content += config.customRules;
  }

  return content;
}

